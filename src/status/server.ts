/**
 * Status / health service.
 *
 * Mirrors the observed behaviour of `status-prod.platocorp.com`:
 *   GET /  ->  text/plain  {"downtime":0,"reason":""}
 * The client checks this around connect time; `downtime: 1` with a `reason`
 * string puts the app into its maintenance screen.
 */
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import Fastify, { type FastifyInstance } from "fastify";
import type { ServerConfig } from "../config/env.js";
import { ARCHETYPES, roster } from "../game/matchmonsters/monsters.js";
import { abilityView } from "../game/matchmonsters/engine.js";
import { kitTags } from "../game/matchmonsters/draft.js";

export interface StatusBody {
  downtime: 0 | 1;
  reason: string;
}

export function buildStatusServer(config: ServerConfig): FastifyInstance {
  const app = Fastify({ logger: false });

  const body = (): StatusBody => ({
    downtime: config.downtime,
    reason: config.maintenanceReason,
  });

  // The real endpoint replies with a JSON document under a text/plain content
  // type, so we serialise by hand and set the header to match exactly.
  app.get("/", async (_req, reply) => {
    reply.header("content-type", "text/plain; charset=utf-8");
    return JSON.stringify(body());
  });

  // Convenience alias for load balancers / uptime checks.
  app.get("/healthz", async () => ({ status: "ok" }));

  // Playable web client: open /play on two devices to battle a friend.
  // The client connects WebSockets same-origin, so no port needs injecting.
  app.get("/play", async (_req, reply) => {
    reply.header("content-type", "text/html; charset=utf-8");
    return loadClientHtml();
  });

  // Monster roster for the client's picker: move text + element archetype.
  app.get("/play/monsters", async () =>
    roster().map((m) => ({
      id: m.id,
      name: m.name,
      element: m.element,
      chargeCost: m.chargeCost,
      ability: abilityView(m, 0),
      archetype: ARCHETYPES[m.element],
      /** Strong vs / weak to / combos with, derived from the kit (draft screen). */
      tags: kitTags(m),
    })),
  );

  // Plotomon creature art module (served to the client).
  // Move/board animations (one animator per effect kind; see web/animators.js).
  app.get("/play/animators.js", async (_req, reply) => {
    reply.header("content-type", "application/javascript; charset=utf-8");
    return loadWebFile("animators.js");
  });

  // Pixel sprites for monsters and gems (generated by art/pixel/build.py).
  app.get("/play/pixelart.js", async (_req, reply) => {
    reply.header("content-type", "application/javascript; charset=utf-8");
    return loadWebFile("pixelart.js");
  });

  app.get("/play/plotomon.js", async (_req, reply) => {
    reply.header("content-type", "application/javascript; charset=utf-8");
    return loadArtJs();
  });

  // Sound and haptics (web/feedback.js), the generated sound set (web/sounds.js),
  // and jsfxr, the synth that plays it (pinned npm dependency).
  for (const name of ["feedback.js", "sounds.js"]) {
    app.get(`/play/${name}`, async (_req, reply) => {
      reply.header("content-type", "application/javascript; charset=utf-8");
      return loadWebFile(name);
    });
  }
  for (const name of ["riffwave.js", "sfxr.js"]) {
    app.get(`/play/${name}`, async (_req, reply) => {
      reply.header("content-type", "application/javascript; charset=utf-8");
      reply.header("cache-control", "public, max-age=86400");
      return loadPackageText(`jsfxr/${name}`);
    });
  }

  // Animate.css (pinned npm dependency): the stock presets monsters react with.
  app.get("/play/animate.min.css", async (_req, reply) => {
    reply.header("content-type", "text/css; charset=utf-8");
    reply.header("cache-control", "public, max-age=86400");
    return loadAnimateCss();
  });

  // Pixel fonts (pinned @fontsource packages): Silkscreen for labels, Pixelify Sans for text.
  app.get<{ Params: { file: string } }>("/play/fonts/:file", async (req, reply) => {
    const m = /^(pixelify-sans|silkscreen)-latin-(400|500|600|700)-normal\.woff2$/.exec(req.params.file);
    if (!m) return reply.code(404).send();
    let font: Buffer;
    try {
      font = loadFont(`@fontsource/${m[1]}/files/${req.params.file}`);
    } catch {
      return reply.code(404).send();
    }
    reply.header("content-type", "font/woff2");
    reply.header("cache-control", "public, max-age=604800, immutable");
    return font;
  });

  return app;
}

const fontCache = new Map<string, Buffer>();
function loadFont(spec: string): Buffer {
  let font = fontCache.get(spec);
  if (!font) {
    font = readFileSync(createRequire(import.meta.url).resolve(spec));
    fontCache.set(spec, font);
  }
  return font;
}

function loadAnimateCss(): string {
  return loadPackageText("animate.css/animate.min.css");
}

/** A text file shipped inside an npm dependency ("pkg/path" or "@scope/pkg/path"), read once. */
const packageTextCache = new Map<string, string>();
function loadPackageText(spec: string): string {
  let text = packageTextCache.get(spec);
  if (text === undefined) {
    const parts = spec.split("/");
    const nameLen = spec.startsWith("@") ? 2 : 1;
    const pkg = parts.slice(0, nameLen).join("/");
    const file = parts.slice(nameLen).join("/");
    const req = createRequire(import.meta.url);
    let root: string;
    try {
      root = dirname(req.resolve(`${pkg}/package.json`));
    } catch {
      root = dirname(req.resolve(pkg)); // "exports" hides package.json: use the main entry's folder
    }
    text = readFileSync(`${root}/${file}`, "utf8");
    packageTextCache.set(spec, text);
  }
  return text;
}

let cachedArt: string | null = null;
function loadArtJs(): string {
  if (cachedArt === null) {
    cachedArt = readFileSync(fileURLToPath(new URL("../../web/plotomon.js", import.meta.url)), "utf8");
  }
  return cachedArt;
}

const webCache = new Map<string, string>();
function loadWebFile(name: string): string {
  let text = webCache.get(name);
  if (text === undefined) {
    text = readFileSync(fileURLToPath(new URL(`../../web/${name}`, import.meta.url)), "utf8");
    webCache.set(name, text);
  }
  return text;
}

let cachedHtml: string | null = null;
function loadClientHtml(): string {
  if (cachedHtml === null) {
    const path = fileURLToPath(new URL("../../web/index.html", import.meta.url));
    cachedHtml = readFileSync(path, "utf8");
  }
  return cachedHtml;
}
