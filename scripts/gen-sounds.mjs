/**
 * Generate Ploto's sounds from jsfxr's stock presets.
 *
 *   npm run sounds        (node scripts/gen-sounds.mjs)
 *
 * Each set is a JSON file next to its owner: Ploto's own (src/platform/sounds.json:
 * lobby taps, confirmations, your turn) and one per game (src/game/<game>/sounds.json).
 * A cue is a jsfxr preset (pickupCoin, laserShoot, hitHurt, ...) with a seed, so
 * the same seed always picks the same variant, optional parameter overrides,
 * how loud it is (vol) and how it vibrates (buzz, ms). Everything is written as
 * jsfxr's compact codes to web/sounds.js; the client synthesises them at runtime
 * (web/feedback.js), the game's own set first, then Ploto's.
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { sfxr } = require("jsfxr");

/**
 * A soft two-note chime: a sine wave (no harsh harmonics) stepping up a fifth,
 * C5 to G5 (~520 -> ~790 Hz), so a cue that plays every turn stays easy on the
 * ears. The stock "jump" preset was a thin pulse sweeping past 1.3 kHz.
 */
const CHIME = {
  wave_type: 2, // sine
  p_base_freq: 0.384, // ~523 Hz
  p_arp_mod: 0.608, // up a fifth
  p_arp_speed: 0.62,
  p_env_sustain: 0.18,
  p_env_punch: 0.25,
  p_env_decay: 0.42,
  p_freq_ramp: 0,
  p_lpf_freq: 1,
  p_hpf_freq: 0,
};

/** Named parameter overrides a cue can ask for ("params": "chime"). */
const PARAMS = { chime: CHIME };
const root = new URL("..", import.meta.url);
const files = [new URL("src/platform/sounds.json", root)];
// Sorted, so web/sounds.js comes out the same on every machine.
for (const dir of readdirSync(new URL("src/game/", root), { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
  const f = new URL(`src/game/${dir.name}/sounds.json`, root);
  if (dir.isDirectory() && existsSync(f)) files.push(f);
}

/** mulberry32: a tiny seeded PRNG, so the same seed always picks the same variant. */
function seeded(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const random = Math.random;
const sets = {};
let count = 0;
/** Stop with a message that names the file and cue, instead of writing a sound that breaks at runtime. */
const fail = (file, msg) => { console.error(`${file.pathname.replace(root.pathname, "")}: ${msg}`); process.exit(1); };
for (const file of files) {
  const { set, cues } = JSON.parse(readFileSync(file, "utf8"));
  if (typeof set !== "string" || !set) fail(file, 'needs a "set" name');
  if (sets[set]) fail(file, `the set "${set}" is already taken (by Ploto's or another game's sounds.json)`);
  sets[set] = {};
  for (const [name, c] of Object.entries(cues)) {
    if (!c.preset) fail(file, `cue "${name}" needs a "preset"`);
    if (typeof c.seed !== "number") fail(file, `cue "${name}" needs a numeric "seed"`);
    if (typeof c.params === "string" && !PARAMS[c.params]) fail(file, `cue "${name}": unknown params "${c.params}" (known: ${Object.keys(PARAMS).join(", ")})`);
    const vol = c.vol ?? 0.5;
    if (typeof vol !== "number" || !(vol > 0 && vol <= 1)) fail(file, `cue "${name}": "vol" must be a number from 0 to 1`);
    const buzz = c.buzz ?? 0;
    Math.random = seeded(c.seed);
    const overrides = typeof c.params === "string" ? PARAMS[c.params] : c.params;
    let generated;
    try { generated = sfxr.generate(c.preset); } catch { fail(file, `cue "${name}": unknown preset "${c.preset}"`); }
    sets[set][name] = { code: sfxr.b58encode(Object.assign(generated, overrides)), vol, buzz };
    count++;
  }
}
Math.random = random;

const out = new URL("../web/sounds.js", import.meta.url);
writeFileSync(
  out,
  "// Generated by scripts/gen-sounds.mjs from src/platform/sounds.json and src/game/*/sounds.json; edit those, not this file.\n" +
    `window.PLOTO_SOUNDS = ${JSON.stringify(sets, null, 2)};\n`,
);
console.log(`${count} sounds in ${Object.keys(sets).length} sets -> web/sounds.js`);
