/**
 * Generate the game's sound effects from jsfxr's stock presets.
 *
 *   node scripts/gen-sounds.mjs
 *
 * jsfxr's preset generators (pickupCoin, laserShoot, hitHurt, ...) randomise
 * every call, so this script seeds Math.random and picks one variant of each,
 * then writes them as jsfxr's compact codes to web/sounds.js. The client
 * synthesises them with jsfxr at runtime. Change a seed to audition another
 * variant of the same preset.
 */
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { sfxr } = require("jsfxr");

/** event -> [jsfxr preset, seed] */
const SOUNDS = {
  select: ["blipSelect", 3], // picking a gem up
  swap: ["click", 5], // two gems trading places
  match: ["pickupCoin", 7], // a match clearing (pitched up per combo step)
  ready: ["powerUp", 11], // a monster reaching full charge
  cast: ["laserShoot", 2], // a move firing
  hit: ["hitHurt", 4], // damage landing
  bigHit: ["explosion", 9], // a heavy hit
  heal: ["synth", 6], // heal or shield
  turn: ["jump", 8], // your turn
  evolve: ["powerUp", 21], // evolution
  ko: ["explosion", 13], // a team fainting
};

/** mulberry32: a tiny seeded PRNG, so the same seed always picks the same variant. */
function seeded(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const random = Math.random;
const codes = {};
for (const [name, [preset, seed]] of Object.entries(SOUNDS)) {
  Math.random = seeded(seed);
  codes[name] = sfxr.b58encode(sfxr.generate(preset));
}
Math.random = random;

const out = new URL("../web/sounds.js", import.meta.url);
writeFileSync(
  out,
  "// Generated by scripts/gen-sounds.mjs from jsfxr's stock presets; edit the seeds there, not this file.\n" +
    `window.MM_SOUNDS = ${JSON.stringify(codes, null, 2)};\n`,
);
console.log(`${Object.keys(codes).length} sounds -> web/sounds.js`);
