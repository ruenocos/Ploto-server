"""
Build every pixel sprite and the game's art module.

  python3 art/pixel/build.py

Writes PNGs to art/pixel/out/ (open them in Aseprite to tweak by hand) and
web/pixelart.js, which the client loads: window.PIXELART = { monsters, gems }
with each sprite as a PNG data URL.
"""
from __future__ import annotations

import base64
import io
import json
from pathlib import Path

import batch1
import batch2
import batch3
import gems

HERE = Path(__file__).resolve().parent
OUT = HERE / "out"
WEB = HERE.parent.parent / "web" / "pixelart.js"

# Sprite name -> monster id in the game roster.
MONSTER_IDS = {
    "pyrup": "ember_pup", "scorchpaw": "cinder_hound", "magmaul": "magma_titan", "emberwing": "phoenix_chick",
    "tidecoil": "tide_serpent", "frostnip": "frost_imp", "krakling": "kraken_pup", "bublob": "bubble_jelly",
    "craggol": "stone_golem", "rubbug": "boulder_beetle", "tremole": "quake_mole", "gemox": "crystal_ox",
    "thornkin": "thorn_sprite", "vinecoil": "vine_lurker", "myconite": "shroom_knight", "petalope": "petal_fawn",
    "lumowl": "prism_owl", "glintling": "dawn_sprite", "lumistag": "lumen_stag", "lumoth": "halo_moth",
}


def data_url(img) -> str:
    buf = io.BytesIO()
    img.save(buf, format="PNG", optimize=True)
    return "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()


def main() -> None:
    OUT.mkdir(exist_ok=True)
    monsters, tiles = {}, {}
    for module in (batch1, batch2, batch3):
        for make in module.SPRITES:
            s = make()
            img = s.render()
            img.save(OUT / f"{s.name}.png")
            monsters[MONSTER_IDS[s.name]] = data_url(img)
    for make in gems.SPRITES:
        s = make()
        img = s.render()
        img.save(OUT / f"gem-{s.name}.png")
        tiles[s.name] = data_url(img)
    missing = set(MONSTER_IDS.values()) - set(monsters)
    assert not missing, f"no sprite for {missing}"
    WEB.write_text(
        "// Generated by art/pixel/build.py; edit the sprite sources there, not this file.\n"
        "// Monsters are 32x32, gems 16x16. Draw them at whole-number scales with image-rendering: pixelated.\n"
        f"window.PIXELART = {json.dumps({'monsters': monsters, 'gems': tiles}, indent=1)};\n"
    )
    print(f"{len(monsters)} monsters, {len(tiles)} gems -> {WEB.relative_to(HERE.parent.parent)} ({WEB.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
